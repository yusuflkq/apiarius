import type { On, SessionMessage, ToolUseSummary } from 'claude-code'
import { expect, mock, test } from 'claude-code/testing'

import * as F from '../hooks/format'
import { emptyGit } from '../hooks/git'
import * as M from '../hooks/model'
import type { DeckAgent, DeckData, DeckSnapshot } from '../types'

/**
 * What a reload can cost the deck, read back from the transcripts: the goal,
 * when the person's last prompt came before the deck tracked goals (or the
 * snapshot was lost), and the result of an agent that ended while the deck
 * reloaded (its SubagentHandback never recorded).
 */

const NOW = 1_700_000_100_000
const HEADLINE = 'Make the deck say where each agent is'
const PROMPT = `${HEADLINE}\n\nKeep the outline native, and the header to one line.`
const REPORT = 'The Files section and the detail block are built and wired into the Agents tab; all checks are green.'
const LONG_REPORT = `${REPORT} ${'Every row was checked on both surfaces. '.repeat(50)}`
const LAST_WORDS = 'All fixed: the parser skips blank lines now, and its test covers them.'

function user(text: string, extra: Partial<SessionMessage> = {}): SessionMessage {
  return { role: 'user', text, toolUses: [], ...extra }
}

function assistant(text: string, toolUses: ToolUseSummary[] = []): SessionMessage {
  return { role: 'assistant', text, toolUses }
}

/** A tool use of an assistant message, answered. */
function use(tool: string, input: Record<string, unknown>, extra: Partial<ToolUseSummary> = {}): ToolUseSummary {
  return { tool_use_id: `toolu_${tool}`, tool, input, text: 'ok', ...extra }
}

/** A user message that carries tool results and nothing else. */
function results(): SessionMessage {
  return user('', { toolResults: [{ tool_use_id: 'toolu_1', text: 'ok', isError: false }] })
}

/** The session's transcript as the engine reads it back: one prompt in the person's words, then notifications, agent messages, command records and tool results. */
const MAIN: SessionMessage[] = [
  user('An older prompt, answered long ago'),
  assistant('Done.'),
  user(PROMPT),
  assistant('Starting a scout.', [use('Agent', { description: 'scout' }, { agentId: 'a-scout' })]),
  results(),
  user('[Image: source: C:\\Users\\me\\images\\2.webp]'),
  user('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>'),
  user('<command-name>/deck</command-name>\n<command-message>deck</command-message>\n<command-args></command-args>'),
  user('Another Claude session sent a message:\n<agent-message from="a-scout">\n[Subagent hand-back] The text below is the final report of a subagent.\n  Found it.\n</agent-message>'),
  user('<task-notification>\n<task-id>a-scout</task-id>\n<status>completed</status>\n</task-notification>'),
  user('[SYSTEM NOTIFICATION] the background shell exited'),
  user('<cross-session-message from="another session">ping</cross-session-message>'),
  user('<system-reminder>The task tools have not been used recently.</system-reminder>'),
  user('  \n\t '),
  assistant('The scout found it.'),
]

/**
 * The engine in Claude Code's place, outside a repository. `restored` is the
 * snapshot a reload finds, `main` the session's transcript, `agents` each
 * agent's (any other is denied); `reads` logs whose transcript the deck read
 * (`main` for the session's), `saved` each snapshot it kept.
 */
function world(on: On, options: { restored?: DeckSnapshot; main?: SessionMessage[]; agents?: Record<string, SessionMessage[]> } = {}) {
  const saved: DeckSnapshot[] = []
  const reads: string[] = []
  mock.store(on)
  on('session.start', ($, e) => ({ cwd: e.cwd }))
  on('command.register', ($, e) => ({ value: { command: e.name } }))
  on('ui.panes', () => ({ value: [] }))
  on('ui.open', () => ({ value: { isPlaced: true } }))
  on('ui.close', () => ({ value: undefined }))
  on('ui.log', () => ({ value: undefined }))
  on('session.id', () => ({ value: 'session-1' }))
  on('session.model', () => ({ value: 'claude-test' }))
  on('session.usage', () => ({ value: { startedAt: NOW - 1_800_000, context: { window: 200_000, tokens: 24_000, percent: 12 }, rateLimits: [] } }))
  on('session.messages', ($, e) => {
    reads.push(e.agentId ?? 'main')
    if (e.agentId === undefined) return { value: options.main ?? [] }
    return { value: options.agents?.[e.agentId] ?? { deny: `${e.agentId}: no transcript this session reads` } }
  })
  on('agent.list', () => ({ value: [] }))
  on('process.run', () => ({ value: { exitCode: 128, stdout: '', stderr: 'not a git repository', isStdoutTruncated: false, isStderrTruncated: false } }))
  let version = options.restored ? 1 : 0
  on('state.get', { plugin: 'agent-deck', key: 'snapshot' }, () => ({ value: { value: options.restored, version } }))
  on('state.set', { plugin: 'agent-deck', key: 'snapshot' }, ($, e) => {
    saved.push(JSON.parse(JSON.stringify(e.value)) as DeckSnapshot)
    version += 1
    return { value: { isSet: true as const, version } }
  })
  return { saved, reads }
}

const START = { surface: 'desktop', isInteractive: true, cwd: '/work' } as const

/** /deck as typed at the prompt. */
function deck(args: string) {
  return { command: 'deck', args, origin: { kind: 'composer' as const }, presentation: { isFullscreen: true, columns: 100 } }
}

/** A snapshot as a reload finds it in `$.state`. */
function snapshot(data: DeckData): DeckSnapshot {
  return { v: M.SNAPSHOT_VERSION, data: M.copyOf(data), view: M.defaultView() }
}

function lastOf(saved: readonly DeckSnapshot[]): DeckData {
  const last = saved[saved.length - 1]
  if (!last) throw new Error('the deck kept no snapshot')
  return last.data
}

/** One of the Orchestrator's agents, as a snapshot holds it. */
function agent(data: DeckData, id: string, startedAt: number, extra: Partial<DeckAgent>): DeckAgent {
  const made = M.newAgent(id, 'agent', id, startedAt, { type: 'general-purpose', parentId: M.MAIN, origin: 'agent', description: `${id}: its task`, ...extra })
  data.agents.push(made)
  return made
}

/** An agent the snapshot holds as ended at `endedAt` with no result: its end came, its hand-back did not. */
function ended(data: DeckData, id: string, endedAt: number, extra: Partial<DeckAgent> = {}): DeckAgent {
  return agent(data, id, endedAt - 60_000, { status: 'completed', endedAt, ...extra })
}

test('a reload with no goal takes the newest prompt in the person`s own words from the transcript, past notifications, agent messages and command records', async ($, on) => {
  const clock = mock.clock(on, { now: NOW })
  const data = M.emptyData(NOW - 1_800_000)
  agent(data, 'a-scout', NOW - 1_200_000, { status: 'completed', endedAt: NOW - 900_000, answer: 'Found it: parse.js line 12.', resultVia: 'answer' })
  agent(data, 'a-fixer', NOW - 600_000, { status: 'running' })
  const { saved, reads } = world(on, { restored: snapshot(data), main: MAIN })

  await $.session.start(START)
  await clock.settle()
  await clock.advance(2000)

  const kept = lastOf(saved)
  const goal = M.goalOf(kept)
  // one goal, in the person's words: the older prompt is no follow-up of it
  expect(kept.goals).toHaveLength(1)
  expect(goal).toMatchObject({ text: PROMPT, headline: HEADLINE, origin: 'recovered', followUps: [] })
  // it takes over the agents the deck held with no goal, and dates from the earliest of them: the plan and the summary count as before
  expect(kept.agents.filter(one => one.kind === 'agent').map(one => one.goal)).toEqual([goal?.id, goal?.id])
  expect(goal?.at).toBe(NOW - 1_200_000)
  expect(M.planOf(kept)).toMatchObject({ source: 'implicit', goal: goal?.id })
  expect(M.planOf(kept).steps).toHaveLength(2)
  expect(M.summaryOf(kept, emptyGit(), NOW)).toMatchObject({ running: 1, done: 1, minutes: 20 })
  // the session's transcript, read once; the scout has its result, the fixer works on
  expect(reads).toEqual(['main'])
})

test('the pane`s first tick looks again: a prompt the transcript holds by then becomes the goal, and later ticks read nothing more', async ($, on) => {
  const clock = mock.clock(on, { now: NOW })
  const main: SessionMessage[] = []
  const { saved, reads } = world(on, { main })

  await $.session.start(START)
  await clock.settle()
  // the start looked and found no prompt; a tick with the pane shut does not look
  main.push(...MAIN)
  await clock.advance(2500)
  expect(reads).toEqual(['main'])

  await $.command.run(deck(''))
  await clock.advance(2500)
  expect(reads).toEqual(['main', 'main'])
  await clock.advance(2000)
  expect(M.goalOf(lastOf(saved))).toMatchObject({ text: PROMPT, headline: HEADLINE, origin: 'recovered' })

  await clock.advance(7500)
  expect(reads).toEqual(['main', 'main'])
})

test('a goal in hand stands: the transcript is not read for one, at the start or when the pane opens', async ($, on) => {
  const clock = mock.clock(on, { now: NOW })
  const data = M.emptyData(NOW - 600_000)
  M.noteGoal(data, 'goal', { text: 'Fix the flaky retry test', origin: 'composer', at: NOW - 300_000 })
  const { saved, reads } = world(on, { restored: snapshot(data), main: MAIN })

  await $.session.start(START)
  await $.command.run(deck(''))
  await clock.advance(5000)

  expect(reads).toEqual([])
  expect(lastOf(saved).goals.map(goal => [goal.text, goal.origin])).toEqual([['Fix the flaky retry test', 'composer']])
  // and the model's own guard: a goal in hand takes no recovered one
  expect(M.noteRecoveredGoal(data, { text: PROMPT, headline: HEADLINE }, NOW)).toBeUndefined()
  expect(data.goals).toHaveLength(1)
})

test('an agent that ended during a reload with no result takes one from its own transcript: its SubagentHandback`s message, else its last words; a denied read leaves it be', async ($, on) => {
  const clock = mock.clock(on, { now: NOW })
  const data = M.emptyData(NOW - 600_000)
  M.noteGoal(data, 'goal', { text: 'Ship v3', origin: 'composer', at: NOW - 500_000 })
  ended(data, 'a-words', NOW - 120_000)
  ended(data, 'a-handback', NOW - 60_000)
  ended(data, 'a-denied', NOW - 30_000)
  ended(data, 'a-answered', NOW - 90_000, { answer: 'Reported already.', resultVia: 'answer' })
  agent(data, 'a-running', NOW - 30_000, { status: 'running' })
  const agents: Record<string, SessionMessage[]> = {
    'a-words': [
      user('Fix the parser.'),
      assistant('Reading it.', [use('Read', { file_path: '/repo/parse.js' })]),
      results(),
      assistant(LAST_WORDS),
      // a message of thinking alone
      assistant(''),
    ],
    'a-handback': [
      user('Build the files section.'),
      assistant('Done; handing back.', [use('SubagentHandback', { message: LONG_REPORT })]),
      results(),
      assistant(''),
    ],
    'a-answered': [assistant('Something else entirely.')],
    'a-running': [assistant('Still at it.')],
  }
  const { saved, reads } = world(on, { restored: snapshot(data), agents })

  await $.session.start(START)
  await clock.settle()
  await clock.advance(2000)

  const kept = lastOf(saved)
  expect(M.agentOf(kept, 'a-words')).toMatchObject({ answer: LAST_WORDS, resultVia: 'stop' })
  // capped like every other result
  expect(M.agentOf(kept, 'a-handback')).toMatchObject({ answer: F.trunc(LONG_REPORT.trim(), M.LIMITS.answerChars), resultVia: 'handback' })
  expect(M.agentOf(kept, 'a-denied')?.answer).toBeUndefined()
  expect(M.agentOf(kept, 'a-answered')).toMatchObject({ answer: 'Reported already.', resultVia: 'answer' })
  // the latest to end read first; one with a result, or still at work, never
  expect(reads).toEqual(['a-denied', 'a-handback', 'a-words'])
  // one result message each, to the agent that started it
  const shown = kept.messages.filter(message => message.kind === 'result').map(message => [message.from, message.to, message.text.length])
  expect(shown).toEqual([
    ['a-handback', M.MAIN, M.LIMITS.messageChars],
    ['a-words', M.MAIN, LAST_WORDS.length],
  ])
})

test('a pass reads at most 12 agents` transcripts, the latest to end first, and none twice: the pane`s first tick reads the rest', async ($, on) => {
  const clock = mock.clock(on, { now: NOW })
  const data = M.emptyData(NOW - 600_000)
  M.noteGoal(data, 'goal', { text: 'Ship v3', origin: 'composer', at: NOW - 500_000 })
  const ids = Array.from({ length: 14 }, (_, i) => `a-${String(i).padStart(2, '0')}`)
  ids.forEach((id, i) => ended(data, id, NOW - 100_000 + i * 1000))
  const newestFirst = [...ids].reverse()
  // no transcripts: each read is denied
  const { reads } = world(on, { restored: snapshot(data) })

  await $.session.start(START)
  await clock.settle()
  expect(reads).toEqual(newestFirst.slice(0, 12))

  await $.command.run(deck(''))
  await clock.advance(2500)
  expect(reads).toEqual(newestFirst)

  // shut and opened again: its first tick finds no agent left unread
  await $.command.run(deck('close'))
  await clock.advance(2500)
  await $.command.run(deck(''))
  await clock.advance(5000)
  expect(reads).toEqual(newestFirst)
})

test('isOwnWords: the person`s words are; a notification, an agent`s message, a command`s record, a reminder, the engine`s own rows, whitespace and image marks alone are not', () => {
  for (const text of ['Fix the flaky test', 'this is what deck probe looks like???', '[Image #1] why is this cut off?', 'why does <Box> wrap here?']) {
    expect(M.isOwnWords(text), text).toBe(true)
  }
  const not = [
    '<task-notification>\n<task-id>a1</task-id>\n</task-notification>',
    'Another Claude session sent a message:\n<agent-message from="a1">hi</agent-message>',
    '[SYSTEM NOTIFICATION] the shell exited',
    '<local-command-caveat>Caveat: generated by the user while running local commands.</local-command-caveat>',
    '<command-name>/deck</command-name>',
    '<system-reminder>Remember the tasks.</system-reminder>',
    'The report follows. [Subagent hand-back] done',
    '<cross-session-message from="x">hi</cross-session-message>',
    '<teammate-message teammate_id="researcher">found it</teammate-message>',
    // a mark counts anywhere in the text, not only at its start
    'Look at this: <system-reminder>pasted</system-reminder>',
    '[Request interrupted by user for tool use]',
    '<local-command-stdout>Agent Deck closed.</local-command-stdout>',
    '<bash-input>git status</bash-input>',
    'Base directory for this skill: C:\\skills\\deck',
    '[Image: source: C:\\Users\\me\\images\\2.webp]',
    '[Image #1] [Image #2]',
    '',
    '  \n\t ',
  ]
  for (const text of not) expect(M.isOwnWords(text), text).toBe(false)
})

test('recoverGoal: the pasted blocks a prompt opens with are cut to their first line, the headline is its first line that says something (80 characters at most), and messages of tool results alone are passed over', () => {
  const pasted = '\n\n<pasted_content id="a702">\nRelease notes draft\nVersion: 3.2.0\n</pasted_content id="a702">\n<pasted_content>\n\nOwner: platform team\nDue: Friday\n</pasted_content>\n\ncan you cut this one to 200 words?'
  expect(M.recoverGoal([user(pasted), assistant('Looking.')])).toEqual({
    text: 'Release notes draft\nOwner: platform team\ncan you cut this one to 200 words?',
    headline: 'Release notes draft',
  })
  const words = 'word '.repeat(40).trim()
  const long = M.recoverGoal([user(`## ${words}\nthe rest`)])
  expect(long?.headline).toBe(F.trunc(words, 80))
  expect(Array.from(long?.headline ?? '')).toHaveLength(80)
  expect(M.recoverGoal([user('Fix it'), assistant('', [use('Bash', { command: 'ls' })]), results(), user('[Image: source: C:\\a.png]')])?.text).toBe('Fix it')
  expect(M.recoverGoal([user('<task-notification>x</task-notification>'), results(), assistant('ok')])).toBeUndefined()
})

test('recoverResult: the last SubagentHandback`s message wins, one that errored does not count, and a last message of tool calls alone says nothing', () => {
  const handedBack = [assistant('Reading.', [use('SubagentHandback', { message: 'First report.' })]), assistant('More words.', [use('SubagentHandback', { message: REPORT })]), assistant('Trailing words.')]
  expect(M.recoverResult(handedBack)).toEqual({ text: REPORT, via: 'handback' })
  expect(M.recoverResult([assistant(LAST_WORDS), assistant('', [use('SubagentHandback', { message: REPORT }, { isError: true })])])).toBeUndefined()
  expect(M.recoverResult([assistant(LAST_WORDS), assistant('', [use('Bash', { command: 'npm test' })]), results()])).toBeUndefined()
  expect(M.recoverResult([user('Go.'), assistant(LAST_WORDS), assistant('')])).toEqual({ text: LAST_WORDS, via: 'stop' })
  expect(M.recoverResult([])).toBeUndefined()
})
